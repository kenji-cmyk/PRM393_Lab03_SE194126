[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [ValidateSet('android', 'web')]
    [string]$Platform,
    [string]$TokenFile,
    [ValidatePattern('^[A-Za-z0-9 _.-]{1,64}$')]
    [string]$DisplayName = "VetaLife debug $env:COMPUTERNAME"
)

$ErrorActionPreference = 'Stop'
$projectId = 'vetalife-24f03'
$appId = if ($Platform -eq 'android') {
    '1:455537300059:android:6bf4a62f2e23bb6b91257e'
} else {
    '1:455537300059:web:74e2fcd06bfd330291257e'
}
$firebaseCommand = Get-Command firebase.cmd -ErrorAction Stop
$previousExperiments = $env:FIREBASE_CLI_EXPERIMENTS
$debugToken = $null
$cliOutput = $null

try {
    if ($TokenFile) {
        $debugToken = (Get-Content -LiteralPath $TokenFile -Raw -Encoding UTF8).Trim()
    } else {
        $secureToken = Read-Host 'Paste the App Check debug token from this app (input hidden)' -AsSecureString
        $tokenPointer = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secureToken)
        try {
            $debugToken = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($tokenPointer).Trim()
        } finally {
            [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($tokenPointer)
            $secureToken.Dispose()
        }
    }
    if ($debugToken -notmatch '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$') {
        throw 'Expected the UUID debug token generated by Firebase App Check, not a Gemini API key or an App Check JWT.'
    }

    $env:FIREBASE_CLI_EXPERIMENTS = (@($previousExperiments -split ',') + 'appcheckadmin' |
        Where-Object { $_ } | Select-Object -Unique) -join ','
    # Capture CLI output: its resource ID can contain sensitive debug-token data.
    # The token is passed as an argument, never interpolated into shell code.
    try {
        $cliOutput = & $firebaseCommand.Source appcheck:debugtokens:create $debugToken `
            --app $appId --display-name $DisplayName --project $projectId --non-interactive --json 2>&1
    } catch {
        # Windows PowerShell can throw on native stderr before exit-code handling.
        # Never propagate the native ErrorRecord, which may contain the token.
        throw 'Registration failed. Check firebase login, project access and the display name in Firebase Console; CLI details were withheld to protect the debug token.'
    }
    if ($LASTEXITCODE -ne 0) {
        throw 'Registration failed. Check firebase login, project access and the display name. An existing display name is not overwritten; use a new name or manage it in Firebase Console.'
    }
    Write-Host "Registered App Check debug token for VetaLife $Platform in $projectId."
    Write-Host 'Restart the debug app, then retry meal recognition. Manage or revoke this token in Firebase Console > App Check > Apps > Manage debug tokens.'
} finally {
    $env:FIREBASE_CLI_EXPERIMENTS = $previousExperiments
    $debugToken = $null
    $cliOutput = $null
}
